// ============================================================================
// 3. UTM CAMPAIGN LINKS CSV COMPILER (For Phase 9 Master .ZIP Bundle)
// ============================================================================

export function compileUtmCampaignCsv(
  project: CanonicalBlogProjectState
): string {
  const { slug } = resolveCanonicalAndSlug(project);
  const rows = [
    ["Channel", "UTM_Campaign_URL", "Campaign_Slug"],
    ...(project.distributionPack.utmCampaignLinks || []).map((item) => [
      `"${String(item.channel || "").replace(/"/g, '""')}"`,
      `"${String(item.utmUrl || "").replace(/"/g, '""')}"`,
      `"${slug}"`,
    ]),
  ];
  return rows.map((r) => r.join(",")).join("\n");
}

