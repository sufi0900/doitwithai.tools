export function compileEmbeddableQuizHtml(
  project: CanonicalBlogProjectState
): string {
  const { canonicalUrl } = resolveCanonicalAndSlug(project);
  const questions = project.quizQuestions || [];

  const serializedQuestions = JSON.stringify(
    questions.map((q, idx) => ({
      id: q.id || `q-${idx + 1}`,
      question: q.question,
      options: q.options,
      correctIndex: q.correctIndex,
      explanation: q.explanation,
    }))
  );

  return [
    `<!-- ========================================================================== -->`,
    `<!-- Self-Contained Interactive Reader Comprehension Quiz Widget               -->`,
    `<!-- Generated by DoItWithAI.tools (/tools/article-to-quiz-test-generator)     -->`,
    `<!-- ========================================================================== -->`,
    `<section class="diwai-quiz-widget" aria-label="Interactive Reader Comprehension Quiz" style="font-family: system-ui, -apple-system, sans-serif; background: #0f172a; color: #f8fafc; border: 1px solid #334155; border-radius: 16px; padding: 24px; margin: 32px 0; max-width: 840px;">`,
    `  <div style="display: flex; flex-wrap: wrap; align-items: center; justify-content: space-between; gap: 12px; border-bottom: 1px solid #1e293b; padding-bottom: 16px; margin-bottom: 20px;">`,
    `    <div>`,
    `      <span style="display: inline-block; background: rgba(99, 102, 241, 0.15); color: #a5b4fc; border: 1px solid rgba(99, 102, 241, 0.35); border-radius: 999px; padding: 4px 12px; font-size: 11px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em;">Interactive Knowledge Check</span>`,
    `      <h2 style="margin: 8px 0 4px; font-size: 20px; font-weight: 800; color: #ffffff;">Test Your Mastery: ${escapeHtml(project.metaPack.h1Title)}</h2>`,
    `      <p style="margin: 0; font-size: 13px; color: #94a3b8;">Answer ${questions.length} quick questions to verify your takeaways from this guide.</p>`,
    `    </div>`,
    `    <div id="diwai-quiz-score-pill" style="background: #1e293b; border: 1px solid #334155; border-radius: 12px; padding: 8px 14px; font-size: 13px; font-weight: 700; color: #34d399;">`,
    `      Score: 0 / ${questions.length}`,
    `    </div>`,
    `  </div>`,
    ``,
    `  <div id="diwai-quiz-questions-root"></div>`,
    ``,
    `  <div style="display: flex; flex-wrap: wrap; align-items: center; justify-content: space-between; gap: 12px; margin-top: 20px; padding-top: 16px; border-top: 1px solid #1e293b; font-size: 12px; color: #94a3b8;">`,
    `    <button type="button" id="diwai-quiz-reset-btn" style="background: #312e81; color: #e0e7ff; border: 1px solid #4f46e5; border-radius: 10px; padding: 8px 16px; font-size: 12px; font-weight: 700; cursor: pointer;">↻ Reset Quiz</button>`,
    `    <span>Powered by <a href="${escapeHtml(canonicalUrl)}" style="color: #818cf8; text-decoration: underline;">DoItWithAI.tools Interactive Quiz Studio</a></span>`,
    `  </div>`,
    ``,
    `  <script>`,
    `    (function() {`,
    `      var questions = ${serializedQuestions};`,
    `      var answers = {};`,
    `      var root = document.getElementById("diwai-quiz-questions-root");`,
    `      var scorePill = document.getElementById("diwai-quiz-score-pill");`,
    `      var resetBtn = document.getElementById("diwai-quiz-reset-btn");`,
    ``,
    `      function renderQuiz() {`,
    `        if (!root) return;`,
    `        root.innerHTML = "";`,
    `        var correctCount = 0;`,
    `        var answeredCount = 0;`,
    ``,
    `        questions.forEach(function(q, qIdx) {`,
    `          var selected = answers[qIdx];`,
    `          var isAnswered = typeof selected === "number";`,
    `          if (isAnswered) {`,
    `            answeredCount++;`,
    `            if (selected === q.correctIndex) correctCount++;`,
    `          }`,
    ``,
    `          var card = document.createElement("div");`,
    `          card.style.cssText = "background: #020617; border: 1px solid #1e293b; border-radius: 12px; padding: 16px; margin-bottom: 14px;";`,
    ``,
    `          var title = document.createElement("p");`,
    `          title.style.cssText = "margin: 0 0 12px; font-size: 14px; font-weight: 700; color: #f1f5f9;";`,
    `          title.textContent = (qIdx + 1) + ". " + q.question;`,
    `          card.appendChild(title);`,
    ``,
    `          q.options.forEach(function(opt, oIdx) {`,
    `            var btn = document.createElement("button");`,
    `            btn.type = "button";`,
    `            var borderColor = "#1e293b";`,
    `            var bgColor = "#0f172a";`,
    `            var textColor = "#cbd5e1";`,
    `            if (isAnswered) {`,
    `              if (oIdx === q.correctIndex) {`,
    `                borderColor = "#10b981";`,
    `                bgColor = "rgba(16, 185, 129, 0.14)";`,
    `                textColor = "#6ee7b7";`,
    `              } else if (oIdx === selected) {`,
    `                borderColor = "#f43f5e";`,
    `                bgColor = "rgba(244, 63, 94, 0.14)";`,
    `                textColor = "#fda4af";`,
    `              }`,
    `            }`,
    `            btn.style.cssText = "display: block; width: 100%; text-align: left; padding: 10px 14px; margin-bottom: 8px; border-radius: 10px; border: 1px solid " + borderColor + "; background: " + bgColor + "; color: " + textColor + "; font-size: 13px; cursor: pointer;";`,
    `            btn.textContent = String.fromCharCode(65 + oIdx) + ". " + opt;`,
    `            btn.onclick = function() {`,
    `              answers[qIdx] = oIdx;`,
    `              renderQuiz();`,
    `            };`,
    `            card.appendChild(btn);`,
    `          });`,
    ``,
    `          if (isAnswered && q.explanation) {`,
    `            var exp = document.createElement("div");`,
    `            var won = selected === q.correctIndex;`,
    `            exp.style.cssText = "margin-top: 10px; padding: 10px 12px; border-radius: 8px; font-size: 12px; background: " + (won ? "rgba(16,185,129,0.1)" : "rgba(245,158,11,0.1)") + "; color: " + (won ? "#a7f3d0" : "#fde68a") + ";";`,
    `            exp.textContent = (won ? "✓ Correct! " : "💡 Explanation: ") + q.explanation;`,
    `            card.appendChild(exp);`,
    `          }`,
    ``,
    `          root.appendChild(card);`,
    `        });`,
    ``,
    `        if (scorePill) {`,
    `          scorePill.textContent = "Score: " + correctCount + " / " + questions.length + (answeredCount > 0 ? " (" + Math.round((correctCount / questions.length) * 100) + "%)" : "");`,
    `        }`,
    `      }`,
    ``,
    `      if (resetBtn) {`,
    `        resetBtn.onclick = function() {`,
    `          answers = {};`,
    `          renderQuiz();`,
    `        };`,
    `      }`,
    `      renderQuiz();`,
    `    })();`,
    `  </script>`,
    `</section>`,
  ].join("\n");
}

